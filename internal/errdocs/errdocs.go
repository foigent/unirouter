func All() []Doc {
	out := make([]Doc, len(docs))
	copy(out, docs)
	return out
}

func URLForCode(code string) string {
	for _, doc := range docs {
		if doc.Code == code {
			return doc.DocURL
		}
	}
	if code == "" {
		return "/docs#error-unknown"
	}
	return "/docs#error-" + code
}
