// Package modelrouting builds one immutable model execution plan from one
// PostgreSQL MVCC snapshot. Runtime slots/releases remain traffic authority;
// this package does not introduce a second release lifecycle.
package modelrouting

import (
	"context"
	"encoding/json"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/uniroute/unirouter/internal/executionevidence"
)

const (
	legacyCandidateVersion    = "unirouter.runtime-change-candidate.v1"
	canonicalCandidateVersion = "unirouter.runtime-change-candidate.v2"
	legacyCompatibilityOp     = "legacy.any.v1"
)

// TxStarter is deliberately the exact transaction surface the planner needs.
// *pgxpool.Pool satisfies it without an adapter.
type TxStarter interface {
	BeginTx(context.Context, pgx.TxOptions) (pgx.Tx, error)
}

type Request struct {
	Mode                 Mode
	CustomerOrgID        int64
	PublicModel          string
	ModelOperationID     string
	RequiredCapabilities []string
	// SelectionKey must be generated by UniRouter (normally the request ID),
	// never accepted as a client-controlled routing hint.
	SelectionKey string
}

type Plan struct {
	AuthorityMode           Mode
	PublicModelID           int64
	PublicModel             string
	ModelOperationID        string
	RequiredCapabilities    []string
	PublicContextLimit      int
	PublicOutputLimit       int
	ExecutionProfileID      string
	ExecutionProfileVersion string
	TokenizerProfileID      string
	TokenizerProfileVersion string
	ReasoningProfile        string
	CacheUsageProfile       string
	ModelProtocolProfile    string
	SnapshotHash            string
	DatabaseTime            time.Time
	RuntimeReleaseID        int64
	RuntimeReleaseRef       string
	RuntimeStage            string
	SlotVersion             int64
	Routes                  []Route
	Exclusions              []Exclusion
}

// Route contains the execution material required after a route is selected.
// EncryptedSecret is process-local material and is deliberately absent from
// Evidence and from the snapshot hash.
type Route struct {
	ConnectionName          string
	Provider                string
	BaseURL                 string
	AdapterType             string
	AdapterConfig           json.RawMessage
	ProtocolProfileID       string
	ProtocolProfileVersion  string
	PublicPath              string
	ExecutorContractVersion string
	ProductionApprovalID    int64
	UpstreamModel           string
	MaxContext              int
	DefaultMaxOutput        int
	EncryptedSecret         string
	Priority                int
	Weight                  int
	SelectionReason         string
	RequiresProbe           bool
	// Evidence and PublicEvidence are mutually exclusive. Responses/Messages
	// require the explicit V2 envelope; the historical field never carries a
	// public-execution bundle or a V2 digest.
	Evidence       RouteEvidence
	PublicEvidence *PublicRouteEvidence
}

type RouteEvidence = executionevidence.EvidenceV1
type PublicRouteEvidence = executionevidence.EvidenceV2

// CapabilityEvidenceEntry is the bounded, secret-free authority record that
// justified one requested capability for a selected route.
type CapabilityEvidenceEntry = executionevidence.CapabilityEntry

