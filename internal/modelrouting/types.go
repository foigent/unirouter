// CapabilityRequirement is one normalized per-invocation route requirement.
// Origins are retained as evidence; they never create a second capability set.
type CapabilityRequirement struct {
	CapabilityID       string                        `json:"capability_id"`
	Origins            []string                      `json:"origins"`
	FunctionToolChoice *FunctionToolChoiceConstraint `json:"function_tool_choice,omitempty"`
}

// FunctionToolChoiceConstraint is the closed, normalized invocation contract
// needed to validate a provider tool response against the exact request. It is
// valid on tool_choice_auto|required|named requirements; an explicit/effective
// none constraint is carried by the existing function_tools requirement so it
// does not invent a second capability authority. It is part of the same Plan
// snapshot/hash; response handling must never rebuild it from the raw request.
type FunctionToolChoiceConstraint struct {
	DeclaredFunctionNames []string `json:"declared_function_names"`
	SelectedFunctionName  string   `json:"selected_function_name,omitempty"`
}

// CapabilityDeriver interprets one invocation only after the exact immutable
// Profile has been selected inside the Planner's repeatable-read snapshot.
type CapabilityDeriver func(modelprofile.Profile) ([]CapabilityRequirement, error)

// TxStarter is deliberately the exact transaction surface the planner needs.
// *pgxpool.Pool satisfies it without an adapter.
type TxStarter interface {
	BeginTx(context.Context, pgx.TxOptions) (pgx.Tx, error)
}

type Request struct {
	Mode             Mode
	CustomerOrgID    int64
	PublicModel      string
	ModelOperationID string
	// InvocationCapabilities is for trusted callers that already hold a typed,
	// normalized invocation contract. Gateway request paths use the deriver.
	InvocationCapabilities       []CapabilityRequirement
	DeriveInvocationCapabilities CapabilityDeriver
	// SelectionKey must be generated by UniRouter (normally the request ID),
	// never accepted as a client-controlled routing hint.
	SelectionKey string
}

type Plan struct {
	AuthorityMode    Mode
	PublicModelID    int64
	PublicModel      string
	ModelOperationID string
	// CapabilityRequirements is the sole normalized capability authority.
	CapabilityRequirements []CapabilityRequirement
	// RequiredCapabilities is a derived compatibility projection consumed by
	// existing route/evidence code; it must never be independently normalized.
	RequiredCapabilities []string
	PublicContextLimit   int
	PublicOutputLimit    int
	// RequestDefaultOutputLimit is the provider-profile default used only when
	// the client omits an output limit. PublicOutputLimit remains the explicit
	// request ceiling; keeping the two values separate prevents an advertised
	// provider maximum from silently becoming the default billing liability.
	RequestDefaultOutputLimit int
	ExecutionProfileID        string
	ExecutionProfileVersion   string
	TokenizerProfileID        string
	TokenizerProfileVersion   string
	ReasoningProfile          string
	CacheUsageProfile         string
	ModelProtocolProfile      string
	SnapshotHash              string
	DatabaseTime              time.Time
	RuntimeReleaseID          int64
	RuntimeReleaseRef         string
	RuntimeStage              string
	SlotVersion               int64
	Routes                    []Route
	Exclusions                []Exclusion
}

// Route contains the execution material required after a route is selected.
// EncryptedSecret is process-local material and is deliberately absent from
// Evidence and from the snapshot hash.
type Route struct {
	ConnectionName          string
	Provider                string
	BaseURL                 string
	AdapterType             string
	AdapterConfig           json.RawMessage
	ProtocolProfileID       string
	ProtocolProfileVersion  string
	PublicPath              string
	ExecutorContractVersion string
	ProductionApprovalID    int64
	UpstreamModel           string
	MaxContext              int
	DefaultMaxOutput        int
	EncryptedSecret         string
	Priority                int
	Weight                  int
	SelectionReason         string
	RequiresProbe           bool
	// Evidence and PublicEvidence are mutually exclusive. Responses/Messages
	// require the explicit V2 envelope; the historical field never carries a
	// public-execution bundle or a V2 digest.
	Evidence       RouteEvidence
	PublicEvidence *PublicRouteEvidence
}

type RouteEvidence = executionevidence.EvidenceV1
type PublicRouteEvidence = executionevidence.EvidenceV2

// CapabilityEvidenceEntry is the bounded, secret-free authority record that
// justified one requested capability for a selected route.
type CapabilityEvidenceEntry = executionevidence.CapabilityEntry

